import { readFileSync } from "node:fs";
import { render, screen } from "@testing-library/react";
import { it, expect, vi } from "vitest";
import userEvent from "@testing-library/user-event";
import { ChatMessage } from "./managed-agent-chat-parts";
import { i18n } from "@/i18n";

const ids = {
  conversation: "01a1c695-fc7d-70f2-ad7e-4571b621a4f1",
  message: "01a1c695-fc7d-70f2-ad7e-4571b621a4f2",
  image: "01a1c695-fc7d-70f2-ad7e-4571b621a4f3",
};

it("renders agent messages without an assistant logo", async () => {
  await i18n.changeLanguage("en");
  const { container } = render(
    <ChatMessage
      message={{
        id: ids.message,
        conversationId: ids.conversation,
        requestId: ids.message,
        role: "agent",
        content: "Hello",
        version: 1,
        createdAt: "2026-01-01T00:00:00Z",
      }}
    />,
  );
  expect(screen.getByText("Hello")).toBeVisible();
  expect(container.querySelector(".agent-mark")).not.toBeInTheDocument();
});

it("renders images generated by the agent from the conversation endpoint", async () => {
  await i18n.changeLanguage("en");
  render(
    <ChatMessage
      message={{
        id: ids.message,
        conversationId: ids.conversation,
        requestId: ids.message,
        role: "agent",
        content: "Here it is",
        images: [
          { id: ids.image, mediaType: "image/png", description: "Robot bees" },
          { id: ids.message, mediaType: "image/webp", description: null },
        ],
        version: 1,
        createdAt: "2026-01-01T00:00:00Z",
      }}
    />,
  );
  const image = screen.getByRole("img", { name: "Robot bees" });
  expect(image).toHaveAttribute(
    "src",
    `/api/v2/agent-conversations/${ids.conversation}/messages/${ids.message}/images/${ids.image}`,
  );
  expect(image.closest("a")).toHaveAttribute("target", "_blank");
  expect(
    screen.getByRole("img", { name: "Generated image" }),
  ).toBeInTheDocument();
});

it("renders generated files in place without exposing citation markers", async () => {
  await i18n.changeLanguage("en");
  render(
    <ChatMessage
      message={{
        id: ids.message,
        conversationId: ids.conversation,
        requestId: ids.message,
        role: "agent",
        version: 1,
        createdAt: "2026-01-01T00:00:00Z",
        content:
          "Here is your file:\n\n:beeteam-file-citation{index=0}\n\n`code :beeteam-file-citation{index=0}`\n\n[ordinary link](#beeteam-file-0)",
        files: [
          {
            index: 0,
            id: ids.image,
            name: "example.pdf",
            mediaType: "application/pdf",
            sizeBytes: 1200,
            status: "available",
          },
        ],
      }}
    />,
  );
  expect(screen.getByText("example.pdf")).toBeVisible();
  expect(
    screen.getByRole("link", { name: /preview example.pdf/i }),
  ).toHaveAttribute(
    "href",
    expect.stringContaining(`/files/${ids.image}/preview`),
  );
  expect(
    screen.getByRole("link", { name: /download example.pdf/i }),
  ).toHaveAttribute("href", expect.stringContaining(`/files/${ids.image}`));
  expect(
    screen.getByText("code :beeteam-file-citation{index=0}"),
  ).toBeVisible();
  expect(screen.getByRole("link", { name: "ordinary link" })).toHaveAttribute(
    "href",
    "#beeteam-file-0",
  );
});

it("sizes generated file cards to the available message width", async () => {
  await i18n.changeLanguage("en");
  const style = document.createElement("style");
  style.textContent = readFileSync("src/features/managed-agent-chat.css", "utf8");
  document.head.append(style);
  try {
    render(
      <ChatMessage
        message={{
          id: ids.message,
          conversationId: ids.conversation,
          requestId: ids.message,
          role: "agent",
          version: 1,
          createdAt: "2026-01-01T00:00:00Z",
          content: ":beeteam-file-citation{index=0}",
          files: [{ index: 0, name: "example.pdf", status: "unavailable" }],
        }}
      />,
    );
    const card = screen.getByRole("group", { name: "example.pdf" });
    expect(getComputedStyle(card).width).toBe("100%");
  } finally {
    style.remove();
  }
});

it("offers recovery for unavailable historical files", async () => {
  await i18n.changeLanguage("en");
  const recover = vi.fn();
  render(
    <ChatMessage
      onRecover={recover}
      message={{
        id: ids.message,
        conversationId: ids.conversation,
        requestId: ids.message,
        role: "agent",
        version: 1,
        createdAt: "2026-01-01T00:00:00Z",
        content: ":beeteam-file-citation{index=0}",
        files: [{ index: 0, name: "old.pdf", status: "unavailable" }],
      }}
    />,
  );
  await userEvent.click(
    screen.getByRole("button", { name: /recover old.pdf/i }),
  );
  expect(recover).toHaveBeenCalledOnce();
});
